// Emotion sheet: every shot's event beside each main character's face, so expressions can be directed against what
// is actually happening (and reviewed like a screenplay).
// Usage: npx tsx scripts/emotion-sheet.ts sun01 > docs/13-sun01-emotion-sheet.md
import {buildTimeline, formatTimestamp} from '../src/engine/timeline';
import {loadEpisode} from './load-episode';

const id = process.argv[2] ?? 'sun01';
const {episode, voice} = await loadEpisode(id);
const tl = buildTimeline(episode, voice);
const MAIN: Record<string, string> = {you: 'Kai', mira: 'Mira', ito: 'Ito', itoYoung: 'Ito (1983)', mum: 'Mum'};
const SETTLE: Record<string, string> = {surprised: 'alert', scared: 'uneasy'};
const out: string[] = [];
out.push(`# ${episode.youtubeTitle}: emotion sheet`, '');
out.push('Generated by `scripts/emotion-sheet.ts`. Faces that start a shot in a startle (surprised/scared) are drawn settled (alert/uneasy); a startle triggered *inside* a shot peaks ~0.6 s, then settles.', '');
out.push('| time | shot | what happens | beat | faces |', '|---|---|---|---|---|');
for (const s of tl.shots as any[]) {
  const p = s.props ?? {};
  const cast = ((p.cast ?? []) as any[]).filter((c) => MAIN[c.who]);
  const faces = cast.map((c) => {
    const start = c.expr ?? 'neutral';
    const shown = SETTLE[start] ? `${start}→${SETTLE[start]}` : start;
    const changes = ((p.acts ?? []) as any[]).filter((a) => a.who === c.who && a.expr).map((a) => `${a.at}: ${a.expr}`);
    return `**${MAIN[c.who]}** ${shown}${changes.length ? ` (${changes.join(', ')})` : ''}`;
  });
  const said = (s.lines ?? []).map((l: any) => `${l.speaker[0]}${l.speaker.slice(1).toLowerCase()}: “${l.text}”`).join(' ');
  const beat = [s.cue, ...(s.beats ?? []), s.sfx, s.twist ? `twist ${s.twist}` : ''].filter(Boolean).join(', ');
  out.push(`| ${formatTimestamp(s.start)} | ${s.id} | ${(s.action ?? '').replace(/\|/g, '/').slice(0, 110)} ${said ? `<br>${said.slice(0, 140)}` : ''} | ${beat} | ${faces.join('<br>') || '—'} |`);
}
console.log(out.join('\n'));
